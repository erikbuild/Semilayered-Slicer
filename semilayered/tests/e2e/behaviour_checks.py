# ABOUTME: Checks two behaviours of a built macOS app: it holds no update check, and its G-code names upstream's generator.
# ABOUTME: Usage: python3 semilayered/tests/e2e/behaviour_checks.py <path to the .app>
from __future__ import annotations

import plistlib
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Tuple

REPOSITORY_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPOSITORY_ROOT))

from semilayered.release.assets import upstream_version  # noqa: E402

# What the application logs each time it asks the update service for the latest version. The
# closing NUL makes it the whole compiled string, so the longer "updater: checking the ..."
# of another log line does not count.
UPDATE_CHECK_TEXT = b"updater: checking \x00"
# What Semilayered Slicer logs in place of that request.
UPDATE_CHECK_OFF_TEXT = b"updater: update checks are off in this build"

# Settings for a small test print, read from the source tree; the app resolves what they inherit.
MACHINE = "resources/profiles/Unlayered/machine/Unlayered 5 Axis Printer 0.4 nozzle.json"
PROCESS = "resources/profiles/Unlayered/process/0.20mm Standard @Unlayered 5 Axis Printer.json"
FILAMENT = "resources/profiles/OrcaFilamentLibrary/filament/Generic PLA @System.json"
MODEL = "tests/data/20mm_cube.obj"


def executable(app: Path) -> Path:
    with open(app / "Contents" / "Info.plist", "rb") as plist:
        return app / "Contents" / "MacOS" / plistlib.load(plist)["CFBundleExecutable"]


def no_update_check(app: Path) -> Tuple[bool, str]:
    """The executable must not contain the update check, and must contain what replaces it.

    Launching the app cannot show this unattended: a first launch stops at the setup wizard and
    several one-time questions before it would check for updates. The compiled code can. The
    text logged by the update request is only there while the request itself is.
    """
    code = executable(app).read_bytes()
    checks, replaced = code.count(UPDATE_CHECK_TEXT), code.count(UPDATE_CHECK_OFF_TEXT)
    if checks:
        return False, f"the executable still contains the update check (its log text is there {checks} times)"
    if not replaced:
        return False, f"the executable has no update check, but not its replacement either ({UPDATE_CHECK_OFF_TEXT.decode()!r} not found)"
    return True, "the executable contains no update check"


def generator_name(app: Path) -> Tuple[bool, str]:
    """A file the app slices must name the same generator, with the same version, as upstream's build does."""
    expected = f"; generated by Unlayered Slicer {upstream_version(REPOSITORY_ROOT)} on "
    with tempfile.TemporaryDirectory(prefix="semilayered-slice-") as work:
        command = [
            str(executable(app)),
            "--debug", "1",
            "--datadir", f"{work}/data",
            "--load-settings", f"{REPOSITORY_ROOT / MACHINE};{REPOSITORY_ROOT / PROCESS}",
            "--load-filaments", str(REPOSITORY_ROOT / FILAMENT),
            "--slice", "0",
            "--outputdir", f"{work}/out",
            str(REPOSITORY_ROOT / MODEL),
        ]  # fmt: skip
        # The app writes a log file into the directory it is run from.
        sliced = subprocess.run(command, cwd=work, capture_output=True, text=True, timeout=600)
        gcode = Path(work) / "out" / "plate_1.gcode"
        if sliced.returncode != 0 or not gcode.is_file():
            return False, f"slicing failed (exit {sliced.returncode}): {(sliced.stderr or sliced.stdout).strip()[-300:]}"
        with open(gcode, encoding="utf-8", errors="replace") as lines:
            line = next((text.rstrip("\n") for text in lines if text.startswith("; generated by ")), "")
    if not line.startswith(expected):
        return False, f"the G-code says {line!r}; expected it to start with {expected!r}"
    return True, f"the G-code says {line!r}"


def main() -> int:
    if len(sys.argv) != 2 or not (Path(sys.argv[1]) / "Contents" / "Info.plist").is_file():
        print("usage: python3 semilayered/tests/e2e/behaviour_checks.py <path to the .app>", file=sys.stderr)
        return 2
    # Absolute, because the app is run from a temporary directory.
    app = Path(sys.argv[1]).resolve()
    passed = True
    for check in (no_update_check, generator_name):
        ok, detail = check(app)
        passed = passed and ok
        print(f"{'PASS' if ok else 'FAIL'} {check.__name__}: {detail}")
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
